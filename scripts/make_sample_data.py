
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from src.data_loader import SAMPLE_DIR, generate_synthetic_market  # noqa: E402


def main() -> None:
    SAMPLE_DIR.mkdir(parents=True, exist_ok=True)
    market = generate_synthetic_market(seed=42)
    for name, df in market.items():
        path = SAMPLE_DIR / f"{name}.csv"
        df.to_csv(path)
        print(f"wrote {path.relative_to(SAMPLE_DIR.parent.parent)}  ({len(df)} rows)")

    readme = SAMPLE_DIR / "README.md"
    readme.write_text(
        "# Synthetic sample data\n\n"
        "These files are **simulated**, not real market prices. They were generated by\n"
        "`scripts/make_sample_data.py` (seed = 42) using a two-regime random model\n"
        "(see `generate_synthetic_market` in `src/data_loader.py`).\n\n"
        "They exist so that the tests, notebook and dashboard work offline and\n"
        "reproducibly. Results computed on them say nothing about real assets.\n"
        "Synthetic assets have no dividends or splits, so `Adj Close` equals `Close`.\n"
    )
    print(f"wrote {readme.relative_to(SAMPLE_DIR.parent.parent)}")


if __name__ == "__main__":
    main()
