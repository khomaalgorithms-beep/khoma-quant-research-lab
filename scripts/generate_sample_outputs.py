

from __future__ import annotations

import argparse
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

import pandas as pd  # noqa: E402

from src.backtester import run_strategy_backtest  # noqa: E402
from src.data_loader import load_prices  # noqa: E402
from src.portfolio import equal_weights, portfolio_as_backtest, simulate_portfolio  # noqa: E402
from src.reporting import generate_html_report, generate_markdown_report  # noqa: E402
from src.research import (  # noqa: E402
    chronological_split_date,
    cost_sensitivity,
    moving_average_parameter_search,
    train_test_report,
)
from src.risk_metrics import formatted_summary_table, performance_summary  # noqa: E402
from src.strategies import STRATEGIES  # noqa: E402
from src.visualization import static_equity_and_drawdown  # noqa: E402

SETTINGS = {"initial_capital": 10_000.0, "commission_bps": 0.0, "slippage_bps": 5.0, "execution_delay": 1}
RISK_FREE = 0.02


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--source", choices=["synthetic", "yahoo"], default="synthetic")
    parser.add_argument("--asset", default=None, help="asset to backtest (default SYN_STOCKS / SPY)")
    parser.add_argument("--start", default="2005-01-01")
    parser.add_argument("--end", default="2024-12-31")
    parser.add_argument("--out", default=str(ROOT / "sample_outputs"))
    args = parser.parse_args()

    synthetic = args.source == "synthetic"
    tickers = (["SYN_STOCKS", "SYN_TECH", "SYN_SMALLCAP", "SYN_BONDS", "SYN_GOLD"] if synthetic
               else ["SPY", "QQQ", "IWM", "TLT", "GLD"])
    asset = args.asset or tickers[0]
    out = Path(args.out)
    out.mkdir(parents=True, exist_ok=True)
    note = ("SYNTHETIC DATA - generated by a seeded random simulation, not real market prices."
            if synthetic else "Yahoo Finance adjusted close prices.")

    prices, info = load_prices(tickers, args.start, args.end, source=args.source)
    if info["errors"]:
        print("Some tickers failed:", info["errors"])
    if asset not in prices:
        raise SystemExit(f"No data for {asset}; cannot continue.")
    print(f"Loaded {list(prices.columns)}: {prices.index.min().date()} to {prices.index.max().date()}")

    # 1) All three strategies on one asset
    backtests = {name: run_strategy_backtest(prices[asset], name, None, **SETTINGS) for name in STRATEGIES}
    summaries = {name: performance_summary(bt, RISK_FREE) for name, bt in backtests.items()}
    formatted_summary_table(summaries).to_csv(out / "strategy_metrics.csv")

    report_settings = {
        "Asset": asset, "Data source": note,
        "Date range": f"{prices.index.min().date()} to {prices.index.max().date()}",
        "Initial capital": "$10,000", "Strategies": ", ".join(STRATEGIES),
        "Strategy parameters": "defaults (50/200 SMA; 15% target vol, 60-day window, max weight 1.0)",
        "Commission (bps)": 0, "Slippage (bps)": 5,
        "Execution": "signal after close, trade at next day's close",
        "Risk-free rate": f"{RISK_FREE:.0%}",
    }
    (out / "research_report.md").write_text(
        generate_markdown_report(report_settings, backtests, "Buy and Hold", RISK_FREE, note if synthetic else ""))
    (out / "research_report.html").write_text(
        generate_html_report(report_settings, backtests, "Buy and Hold", RISK_FREE, note if synthetic else ""))
    fig = static_equity_and_drawdown({n: bt["equity"] for n, bt in backtests.items()},
                                     f"{asset} - strategies vs buy and hold" + (" (SYNTHETIC DATA)" if synthetic else ""))
    fig.savefig(out / "equity_and_drawdown.png", dpi=120)

    # 2) Train / test split and the parameter search
    split = chronological_split_date(prices.index, 0.6)
    rows = []
    for name in STRATEGIES:
        report = train_test_report(prices[asset], name, None, split, RISK_FREE, **SETTINGS)
        for period in report.columns:
            rows.append({"strategy": name, "period": period,
                         **{k: report.loc[k, period] for k in ["cagr", "annual_volatility", "sharpe", "max_drawdown"]}})
    pd.DataFrame(rows).round(4).to_csv(out / "train_test_split.csv", index=False)
    moving_average_parameter_search(prices[asset], split, risk_free_rate=RISK_FREE, **SETTINGS) \
        .round(4).to_csv(out / "parameter_search.csv", index=False)

    # 3) Cost sensitivity
    cost_sensitivity(prices[asset], "Volatility-Targeted Trend", risk_free_rate=RISK_FREE,
                     initial_capital=10_000.0, execution_delay=1).round(4).to_csv(out / "cost_sensitivity.csv", index=False)

    # 4) Portfolios: 60/40 and equal weight, rebalanced quarterly
    stock, bond = tickers[0], tickers[3]
    portfolios = {
        f"60/40 {stock}/{bond}": {stock: 0.6, bond: 0.4},
        "Equal weight (all 5)": equal_weights(list(prices.columns)),
    }
    port_summaries = {}
    for name, weights in portfolios.items():
        sim = simulate_portfolio(prices[list(weights)], weights, "Q", 5.0, 10_000.0)
        port_summaries[name] = performance_summary(portfolio_as_backtest(sim), RISK_FREE)
    formatted_summary_table(port_summaries).to_csv(out / "portfolio_metrics.csv")

    (out / "README.md").write_text(
        "# Sample research outputs\n\n"
        f"**{note}**\n\n"
        f"Generated by `python scripts/generate_sample_outputs.py --source {args.source}` with "
        "$10,000 starting capital, 5 bps slippage, next-day execution and a 2% risk-free rate.\n\n"
        + ("Because these come from simulated assets, they demonstrate what the tool produces. "
           "They say nothing about real markets. Run the script with `--source yahoo` on a machine "
           "with internet access to produce the same files from real data.\n\n" if synthetic else "")
        + "| File | Contents |\n|---|---|\n"
        "| research_report.md / .html | Full summary report (settings, metrics, drawdowns, limitations) |\n"
        "| equity_and_drawdown.png | Equity curves and drawdowns of the three strategies |\n"
        "| strategy_metrics.csv | All 12 metrics for each strategy |\n"
        "| train_test_split.csv | In-sample vs out-of-sample metrics (60/40 chronological split) |\n"
        "| parameter_search.csv | Moving-average windows ranked by training Sharpe, with test Sharpe |\n"
        "| cost_sensitivity.csv | Volatility-targeted strategy at 0-50 bps trading cost |\n"
        "| portfolio_metrics.csv | 60/40 and equal-weight portfolios, rebalanced quarterly |\n"
    )
    print(f"Wrote outputs to {out}")


if __name__ == "__main__":
    main()
