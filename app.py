def page_performance() -> None:
    st.title("Performance Analytics")
    st.markdown("All three strategies on the same asset, with the same costs and timing.")
    asset = st.selectbox("Asset", assets, key="pa_asset")
    backtests = run_all_strategies(asset, st.session_state.get("last_params", {}))
    summaries = {name: performance_summary(bt, risk_free_rate) for name, bt in backtests.items()}

    st.dataframe(formatted_summary_table(summaries), width="stretch")
    st.plotly_chart(viz.equity_chart({n: bt["equity"] for n, bt in backtests.items()}, "Equity curves"),
                    width="stretch")
    st.plotly_chart(viz.drawdown_chart({n: drawdown_series(bt["strategy_return"].dropna())
                                        for n, bt in backtests.items()}), width="stretch")
    yearly = pd.DataFrame({n: annual_returns(bt["strategy_return"]) for n, bt in backtests.items()})
    st.plotly_chart(viz.annual_returns_chart(yearly), width="stretch")
    st.caption("The first and last years can be partial years.")
    vols = {n: bt["strategy_return"].rolling(63).std() * (252 ** 0.5) for n, bt in backtests.items()}
    st.plotly_chart(viz.rolling_volatility_chart(vols, "63-day rolling volatility of each strategy"),
                    width="stretch")

    st.header("In-sample vs. out-of-sample")
    st.markdown(
        "The data is split **chronologically** (never shuffled). Parameters may only be chosen by "
        "looking at the training period; the test period shows how that choice held up on data it "
        "had not seen."
    )
    fraction = st.slider("Share of history used for training", 0.3, 0.8, 0.6, 0.05)
    split = chronological_split_date(prices.index, fraction)
    st.caption(f"Training: {prices.index.min().date()} to {(split - pd.Timedelta(days=1)).date()} - "
               f"Test: {split.date()} to {prices.index.max().date()}")

    rows = []
    for name in STRATEGIES:
        report = train_test_report(prices[asset], name, st.session_state.get("last_params", {}).get(name),
                                   split, risk_free_rate, **backtest_settings)
        for period in report.columns:
            rows.append({"Strategy": name, "Period": period,
                         **{METRIC_LABELS[k]: format_metric(k, report.loc[k, period])
                            for k in ["cagr", "annual_volatility", "sharpe", "max_drawdown"]}})
    st.dataframe(pd.DataFrame(rows), width="stretch", hide_index=True)

    with st.expander("Overfitting demonstration: searching moving-average windows"):
        st.markdown(
            "Every (short, long) window pair is tested on the **training** period and ranked by its "
            "training Sharpe ratio. Compare the train and test columns: the best in-sample choice is "
            "rarely the best out-of-sample, which is exactly what overfitting looks like."
        )
        search = moving_average_parameter_search(prices[asset], split, risk_free_rate=risk_free_rate,
                                                 **backtest_settings)
        shown = search.copy()
        for col in ["train_sharpe", "test_sharpe"]:
            shown[col] = shown[col].map(lambda v: format_metric("sharpe", v))
        for col in ["train_cagr", "test_cagr"]:
            shown[col] = shown[col].map(lambda v: format_metric("cagr", v))
        st.dataframe(shown, width="stretch", hide_index=True)

    st.header("Transaction cost sensitivity")
    strategy = st.selectbox("Strategy", list(STRATEGIES), index=2, key="cost_strategy")
    other = {k: v for k, v in backtest_settings.items() if k not in ("commission_bps", "slippage_bps")}
    table = cost_sensitivity(prices[asset], strategy, st.session_state.get("last_params", {}).get(strategy),
                             risk_free_rate=risk_free_rate, **other)
    table_fmt = table.assign(
        cagr=table["cagr"].map(lambda v: format_metric("cagr", v)),
        sharpe=table["sharpe"].map(lambda v: format_metric("sharpe", v)),
        max_drawdown=table["max_drawdown"].map(lambda v: format_metric("max_drawdown", v)),
        total_cost_dollars=table["total_cost_dollars"].map(lambda v: f"${v:,.0f}"),
    )
    st.dataframe(table_fmt, width="stretch", hide_index=True)
    st.caption("Cost is the total of commission + slippage, in basis points of each dollar traded.")


