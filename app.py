def page_stress() -> None:
    st.title("Stress Testing")
    st.markdown("How did each strategy behave during difficult periods? Results describe the past only - "
                "surviving one crisis is no guarantee of protection in the next.")
    asset = st.selectbox("Asset", assets, key="st_asset")
    backtests = run_all_strategies(asset, st.session_state.get("last_params", {}))

    if source == "synthetic":
        st.info("Named historical crises (2008, 2020, 2022) are only analyzed with real market data, "
                "because synthetic prices on those dates have nothing to do with what actually happened. "
                "Use the custom window below to explore the synthetic data.")
    else:
        for name, (start, end) in CRISIS_PERIODS.items():
            st.subheader(name)
            if not window_is_covered(prices.index, start, end):
                st.caption(f"Not analyzed: the loaded data does not cover {start} to {end}. "
                           "Extend the date range in the sidebar.")
                continue
            rows = {}
            for strat, bt in backtests.items():
                table, _ = stress_test(bt["strategy_return"], bt["equity"], {name: (start, end)})
                rows[strat] = table.loc[name]
            _show_stress_rows(rows)
            st.plotly_chart(viz.equity_chart(
                {n: bt["equity"].loc[pd.Timestamp(start) - pd.Timedelta(days=30):pd.Timestamp(end) + pd.Timedelta(days=180)]
                 for n, bt in backtests.items()}, f"{name}: equity around the window"), width="stretch")

