def page_portfolio() -> None:
    st.title("Portfolio Research")
    if len(assets) < 2:
        st.info("Load at least two assets to build a portfolio.")
        return

    chosen = st.multiselect("Assets in the portfolio", assets, default=assets)
    if len(chosen) < 2:
        st.info("Pick at least two assets.")
        return

    mode = st.radio("Weights", ["Equal weight", "Custom weights"], horizontal=True, key="pf_mode")
    if mode == "Equal weight":
        weights = equal_weights(chosen)
    else:
        cols = st.columns(len(chosen))
        raw = {t: col.number_input(f"{t} (%)", 0.0, 100.0, round(100 / len(chosen), 1), step=5.0, key=f"w_{t}")
               for col, t in zip(cols, chosen)}
        if sum(raw.values()) <= 0:
            st.error("At least one weight must be above zero.")
            return
        weights = normalize_weights(raw)
        if abs(sum(raw.values()) - 100) > 0.01:
            st.caption(f"Your weights add up to {sum(raw.values()):.1f}%, so they were scaled to 100%.")

    c1, c2 = st.columns(2)
    rebalance_label = c1.selectbox("Rebalancing", list(REBALANCE_OPTIONS), key="pf_rebalance")
    cost = c2.number_input("Rebalancing cost (bps)", 0.0, 100.0, commission_bps + slippage_bps, step=1.0)
    rebalance = REBALANCE_OPTIONS[rebalance_label]
    st.caption("Weights are fixed targets chosen by you - no past returns are used to pick them. "
               + ("Between rebalances the weights drift with prices." if rebalance else
                  "With no rebalancing, the weights drift freely after the first purchase."))

    subset = prices[chosen]
    sims = {
        "Your portfolio": simulate_portfolio(subset, weights, rebalance, cost, initial_capital),
        "Equal weight": simulate_portfolio(subset, equal_weights(chosen), rebalance, cost, initial_capital),
    }
    summaries = {name: performance_summary(portfolio_as_backtest(sim), risk_free_rate) for name, sim in sims.items()}
    for t in chosen:  # each asset on its own, for comparison
        single = simulate_portfolio(subset[[t]], {t: 1.0}, None, cost, initial_capital)
        summaries[f"{t} only"] = performance_summary(portfolio_as_backtest(single), risk_free_rate)

    st.dataframe(formatted_summary_table(summaries).drop(index=["Average exposure"]), width="stretch")
    st.plotly_chart(viz.equity_chart({n: s["result"]["equity"] for n, s in sims.items()}, "Portfolio value"),
                    width="stretch")
    st.plotly_chart(viz.drawdown_chart({n: drawdown_series(s["result"]["portfolio_return"])
                                        for n, s in sims.items()}), width="stretch")

    st.header("Diversification")
    d1, d2, d3 = st.columns(3)
    port_vol = portfolio_volatility(weights, subset)
    avg_vol = sum(weights[t] * subset[t].pct_change().std() * 252 ** 0.5 for t in chosen)
    d1.metric("Portfolio volatility (fixed weights)", f"{port_vol:.1%}")
    d2.metric("Weighted average of asset volatilities", f"{avg_vol:.1%}")
    d3.metric("Diversification ratio", f"{diversification_ratio(weights, subset):.2f}")
    st.caption("If every asset were perfectly correlated, the first two numbers would be equal and the "
               "ratio would be 1.00. The gap is the risk removed by combining assets.")

    left, right = st.columns(2)
    left.plotly_chart(viz.correlation_heatmap(correlation_matrix(subset)), width="stretch")
    rc = risk_contributions(weights, subset)
    right.plotly_chart(viz.bar_chart(rc["risk_contribution"], "Share of portfolio risk from each asset"),
                       width="stretch")
    contrib = return_contribution_summary(sims["Your portfolio"])
    st.plotly_chart(viz.bar_chart(contrib, "Return contribution (sum of daily weight x return)"),
                    width="stretch")

    weights_path = sims["Your portfolio"]["weights"]
    fig = viz.equity_chart({t: weights_path[t] for t in chosen}, "Actual weights over time")
    fig.update_yaxes(tickformat=".0%", title="Weight")
    fig.update_traces(hovertemplate="%{y:.1%}")
    st.plotly_chart(fig, width="stretch")


