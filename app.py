@st.cache_data(show_spinner="Loading price data...")
def cached_single_ticker(ticker: str, start: date, end: date, source: str) -> tuple[pd.Series, dict]:
    """
    Load one ticker. Failures RAISE instead of returning, because Streamlit
    does not cache exceptions - so a failed download is retried next time
    instead of being remembered as "no data".
    """
    prices, info = load_prices([ticker], start, end, source=source)
    if prices.empty:
        raise RuntimeError(next(iter(info["errors"].values()), "unknown error"))
    return prices.iloc[:, 0], info["reports"][prices.columns[0]]


def cached_prices(tickers: tuple[str, ...], start: date, end: date, source: str):
    series, reports, errors = {}, {}, {}
    for ticker in tickers:
        try:
            series[ticker.upper()], reports[ticker.upper()] = cached_single_ticker(ticker, start, end, source)
        except RuntimeError as exc:
            errors[ticker.upper()] = str(exc)
    if not series:
        return pd.DataFrame(), {"reports": reports, "errors": errors, "dates_dropped_in_alignment": 0}
    prices, dropped = align_prices(series)
    return prices, {"reports": reports, "errors": errors, "dates_dropped_in_alignment": dropped}


@st.cache_data(show_spinner=False)
def cached_backtest(prices: pd.Series, strategy: str, params: tuple, settings: tuple) -> pd.DataFrame:
    return run_strategy_backtest(prices, strategy, dict(params), **dict(settings))


