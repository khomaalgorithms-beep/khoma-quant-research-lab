def strategy_param_inputs(strategy: str, key: str) -> dict:
    """Draw an input box for each tunable parameter of a strategy."""
    params = {}
    defaults = STRATEGIES[strategy]["params"]
    if not defaults:
        return params
    cols = st.columns(len(defaults))
    for col, (name, default) in zip(cols, defaults.items()):
        label = name.replace("_", " ").capitalize()
        if isinstance(default, int):
            params[name] = int(col.number_input(label, 2, 400, default, step=5, key=f"{key}_{name}"))
        else:
            params[name] = float(col.number_input(label, 0.01, 1.0, default, step=0.01, key=f"{key}_{name}"))
    return params


def run_all_strategies(asset: str, params_by_strategy: dict[str, dict]) -> dict[str, pd.DataFrame]:
    return {
        name: cached_backtest(prices[asset], name, tuple(sorted(params_by_strategy.get(name, {}).items())),
                              settings_key)
        for name in STRATEGIES
    }


def metric_tiles(summary: dict, benchmark: dict | None = None) -> None:
    keys = ["cagr", "annual_volatility", "sharpe", "max_drawdown", "avg_exposure"]
    for col, key in zip(st.columns(len(keys)), keys):
        delta = None
        if benchmark is not None and pd.notna(summary[key]) and pd.notna(benchmark[key]):
            diff = summary[key] - benchmark[key]
            delta = f"{diff:+.2f} vs B&H" if key == "sharpe" else f"{diff:+.1%} vs B&H"
        col.metric(METRIC_LABELS[key], format_metric(key, summary[key]), delta, delta_color="off")


